// 본문 글의 **굵게** 는 상세 카드에서 굵은 글씨로 그린다.

export type RuleIcon = "book" | "person" | "badge";

/** 목록 한 줄. sub 가 있으면 그 아래 한 단계 들여 쓴 목록 */
export type RuleItem = string | { text: string; sub: string[] };

export interface RuleSection {
  /** 소제목 (이모지 포함 가능) */
  heading: string;
  /** 소제목 아래 한두 문장 */
  lead?: string;
  items?: RuleItem[];
  /** true 면 번호 목록 */
  ordered?: boolean;
  /** 목록 뒤에 붙는 한 문장 */
  after?: string;
}

export interface RuleDoc {
  /** 상세 카드 주소 (?rule=) */
  slug: string;
  title: string;
  icon: RuleIcon;
  /** 맨 위 안내 상자 */
  intro?: string;
  sections: RuleSection[];
  /** 맨 아래 강조 문구 */
  note?: string;
}

